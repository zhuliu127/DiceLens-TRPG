  function shuffle(a) {
    var out = a.slice();
    for (var i = out.length - 1; i > 0; i--) {
      var j = rnd(i + 1), t = out[i]; out[i] = out[j]; out[j] = t;
    }
    return out;
  }

  /** 带「同批去重」的抽取：ctx.used[key] 记录已用过的下标，优先挑没用过的 */
  function pickFrom(pool, ctx, key) {
    if (!pool || !pool.length) return null;
    if (!ctx) return pick(pool);
    var u = ctx.used[key] || (ctx.used[key] = {});
    var avail = [];
    for (var i = 0; i < pool.length; i++) if (!u[i]) avail.push(i);
    if (!avail.length) {
      u = ctx.used[key] = {};
      avail = [];
      for (var j = 0; j < pool.length; j++) avail.push(j);
    }
    var idx = avail[rnd(avail.length)];
    u[idx] = true;
    return pool[idx];
  }

